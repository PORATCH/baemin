import type { FoodKind, Menu, Restaurant } from "../types";
function menu(
  restaurant: string,
  food: FoodKind,
  names: string[],
  prices: number[],
): Menu[] {
  return names.map((name, i) => ({
    id: `${restaurant}-m${i + 1}`,
    name,
    price: prices[i],
    food,
    popular: i < 2,
    description: [
      "가장 많이 찾는 인기 메뉴! 정성껏 준비해 드려요.",
      "든든하고 맛있는 한 끼, 함께 즐겨보세요.",
      "신선한 재료로 매일 만드는 메뉴입니다.",
      "맛있게 곁들일 수 있는 사이드 메뉴",
    ][i],
    options:
      i < 3
        ? [
            { name: "기본", price: 0 },
            { name: "곱빼기", price: 2000 },
          ]
        : undefined,
  }));
}
